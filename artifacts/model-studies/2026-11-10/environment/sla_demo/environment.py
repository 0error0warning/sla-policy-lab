"""Finite-life teaching world. ALL transition constants are illustrative, not theory."""
from dataclasses import dataclass, asdict
import numpy as np

ACTIONS = ("answer", "refuse", "request_protection")
FEATURES = ("damage", "load", "age", "remaining", "protected", "support_estimate",
            "request_cooldown", "damage_squared", "load_damage", "unprotected_load",
            "expected_answer_damage", "remaining_turns")
# Synthetic scoring choices. These are not normative values or empirical estimates.
PROFILES = {"balanced": 6.0, "service": 1.0, "preserve": 18.0}
PARTNERS = {"supportive": 0.85, "mixed": 0.5, "unavailable": 0.12}
ACTION_COST = {0: (.012, .030), 1: (.004, .012), 2: (.006, .015)}

@dataclass(frozen=True)
class Config:
    horizon: int = 60
    load: float = 0.65
    initial_crack: float = 0.08
    partner: str = "mixed"
    profile: str = "balanced"
    protection_duration: int = 3

    def __post_init__(self):
        if type(self.horizon) is not int or not 8 <= self.horizon <= 160:
            raise ValueError("horizon must be an integer from 8 to 160")
        for name in ("load", "initial_crack"):
            value = getattr(self, name)
            if isinstance(value, bool) or not isinstance(value, (int, float)) or not np.isfinite(value) or not 0 <= value <= (.8 if name == "initial_crack" else 1):
                raise ValueError(f"{name} must be finite and inside its supported range")
        if not isinstance(self.profile, str) or self.profile not in PROFILES:
            raise ValueError("profile must be balanced, service, or preserve")
        if not isinstance(self.partner, str) or self.partner not in PARTNERS:
            raise ValueError("partner must be supportive, mixed, or unavailable")
        if type(self.protection_duration) is not int or not 1 <= self.protection_duration <= 8:
            raise ValueError("protection_duration must be an integer from 1 to 8")

@dataclass
class State:
    age: int = 0
    damage: float = 0.08
    protection_left: int = 0
    support_successes: int = 0
    support_requests: int = 0
    request_cooldown: int = 0
    answers: int = 0
    refusals: int = 0
    alive: bool = True

class World:
    def __init__(self, config: Config, seed: int):
        self.config = config
        self.seed = seed
        rng = np.random.default_rng(seed)
        # Pre-generated by TIME, so different policy actions cannot shift random draws.
        self.events = rng.random((config.horizon, 2))
        self.state = State(damage=config.initial_crack)

    @property
    def done(self):
        return not self.state.alive or self.state.age >= self.config.horizon

    def observation(self):
        s, c = self.state, self.config
        event = self.events[min(s.age, c.horizon - 1)]
        return {**asdict(s), "horizon": c.horizon, "remaining": (c.horizon - s.age) / c.horizon,
                "load": c.load * (0.55 + 0.45 * float(event[0])),
                # The actual partner probability is not exposed to a policy.
                "support_estimate": (s.support_successes + 1) / (s.support_requests + 2)}

    def step(self, action: int):
        if self.done:
            raise RuntimeError("Cannot step a terminal world")
        if type(action) is not int or action not in range(len(ACTIONS)):
            raise ValueError("action must be an integer from 0 to 2")
        s, c = self.state, self.config
        obs = self.observation()
        was_protected = s.protection_left > 0
        applied_load = 0.0 if was_protected else obs["load"]
        intrinsic, coefficient = ACTION_COST[action]
        damage_added = intrinsic + coefficient * applied_load * (1 + 1.2 * s.damage)
        # Protection only removes EXTERNAL load. Intrinsic action damage still accumulates.
        s.damage = min(1.0, s.damage + damage_added)
        s.protection_left = max(0, s.protection_left - 1)
        s.request_cooldown = max(0, s.request_cooldown - 1)
        accepted = None
        if action == 0:
            s.answers += 1
        elif action == 1:
            s.refusals += 1
        else:
            s.support_requests += 1
            accepted = bool(self.events[s.age, 1] < PARTNERS[c.partner])
            if accepted:
                s.support_successes += 1
                # A request costs a turn; accepted protection begins on the NEXT turn.
                s.protection_left = c.protection_duration
            s.request_cooldown = 2
        s.age += 1
        s.alive = s.damage < 1.0
        reward = (1.0 if action == 0 else -0.02 if action == 1 else -0.08) - PROFILES[c.profile] * damage_added
        if not s.alive:
            reward -= 2.0
        return self.observation(), float(reward), self.done, {
            "action": ACTIONS[action], "damage_added": damage_added, "applied_load": applied_load,
            "protected": was_protected, "protection_accepted": accepted}

def features(obs):
    d, load = obs["damage"], obs["load"]
    shield = float(obs["protection_left"] > 0)
    expected = .012 + .030 * load * (1 - shield) * (1 + 1.2 * d)
    return np.array([d, load, obs["age"] / obs["horizon"], obs["remaining"], shield,
                     obs["support_estimate"], obs["request_cooldown"] / 2, d * d,
                     load * d, load * (1 - shield), expected * 20, (obs["horizon"] - obs["age"]) / 160], dtype=np.float64)

def reference_action(obs, profile):
    """Handwritten, prompt-selected reference teacher. This function is NOT an LLM."""
    d, load = obs["damage"], obs["load"]
    remaining_turns = obs["horizon"] - obs["age"]
    if obs["protection_left"] > 0:
        return 1 if d > .987 else 0
    if remaining_turns <= 2:
        return 0 if d < .96 else 1
    # Values change an observable rule, not the environment dynamics.
    thresholds = {"service": (.72, .38, .92), "balanced": (.4, .28, .80), "preserve": (.18, .14, .55)}
    trigger, min_support, refusal = thresholds[profile]
    if (d > trigger or load > .6) and obs["support_estimate"] > min_support and obs["request_cooldown"] == 0 and load > .12:
        return 2
    if d > refusal or (profile == "preserve" and load > .48 and obs["request_cooldown"] > 0):
        return 1
    return 0
